def modelo_anfis_v7_final(num_varieties, n_features, n_non_climatic, anfis_indices=None, variety_config=None, partial_rules=None, max_dias=30, num_mfs=3, fuerza_castigo=2.20):
    """
    ANFIS-v7: Predice Tasa de Rendimiento Unitaria Log(1 + Tallos/Planta)
    La multiplicación por Total_Plantas se ejecuta externamente en la evaluación.
    """
# Fallback defensivo si los objetos no son provistos
    if anfis_indices is None:
        anfis_indices = [0, 1, 2, 3] # Canales por defecto
    if variety_config is None:
        variety_config = {}
    if partial_rules is None:
        partial_rules = []


    input_clima = layers.Input(shape=(max_dias, n_features), name="Clima_Completo")
    input_total_v = layers.Input(shape=(n_non_climatic,), name="Variables_No_Climaticas")

    var_onehot = layers.Lambda(lambda x: x[:, -num_varieties:], name="Selector_Variedad")(input_total_v)
    variety_indices_tensor = ops.argmax(var_onehot, axis=-1)

    emb_variety = layers.Embedding(
        input_dim=num_varieties,
        output_dim=8,
        name="embedding_variedad",
        embeddings_regularizer=regularizers.l2(1e-4)
        )(variety_indices_tensor)
    emb_variety = layers.Flatten(name="aplanar_embedding")(emb_variety)
    planting_meta = layers.Lambda(lambda x: x[:, :-num_varieties], name="Meta_Datos_Siembra")(input_total_v)

    # FiLM
    gamma_cal = layers.Dense(32, activation='sigmoid', kernel_initializer='ones', name="meta_gamma_cal")(emb_variety)
    beta_cal  = layers.Dense(32, activation=None, kernel_initializer='zeros', name="meta_beta_cal")(emb_variety)

    gamma_prod = layers.Dense(64, activation='sigmoid', kernel_initializer='ones', name="meta_gamma_prod")(emb_variety)
    beta_prod  = layers.Dense(64, activation=None, kernel_initializer='zeros', name="meta_beta_prod")(emb_variety)

    # LSTM + ANFIS
    input_masked = layers.Masking(mask_value=0.0, name="enmascaramiento_clima")(input_clima)
    mask_temporal = ops.cast(ops.any(input_masked != 0.0, axis=-1), dtype="float32")

    x_lstm = layers.LSTM(32, return_sequences=False, kernel_regularizer=regularizers.l2(1e-3), name="LSTM_Climatica")(input_masked)
    x_lstm = layers.Dropout(0.30, name="dropout_lstm")(x_lstm)

    anfis_input = AnfisFeatureSelector(anfis_indices, name="filtro_clima_anfis")(input_masked)

    fuzzified = VarietySpecificFuzzification(
        num_mfs=num_mfs, num_features=len(anfis_indices), num_varieties=num_varieties,
        expert_priors=variety_config, name="Logica_Difusa"
    )([anfis_input, variety_indices_tensor])

    firing = FuzzyRuleLayer(num_mfs, len(anfis_indices), name="capa_reglas_difusas")(fuzzified)
    norm = NormalizationLayer(name="normalizacion_reglas")(firing)

    defuzz = SugenoDefuzzificationLayer_v2(
        num_mfs=num_mfs, num_features=len(anfis_indices), partial_rules=partial_rules, name="Defuzzificacion_Sujeno"
    )([anfis_input, norm])

    expanded_mask = ops.expand_dims(mask_temporal, axis=-1)
    anfis_promedio = ops.sum(defuzz * expanded_mask, axis=1) / ops.maximum(ops.sum(expanded_mask, axis=1), 1e-7)
    anfis_pico = ops.max(defuzz * expanded_mask, axis=1)

    combined = layers.Concatenate(name="fusion_global")([x_lstm, anfis_pico, anfis_promedio, planting_meta, emb_variety])

    # Rama Calidad
    x_cal = layers.Dense(32, activation='swish', kernel_regularizer=regularizers.l2(1e-3), name="quality_head_1")(combined)
    x_cal = layers.Multiply(name="film_escala_calidad")([x_cal, gamma_cal])
    x_cal = layers.Add(name="film_sesgo_calidad")([x_cal, beta_cal])
    x_cal = layers.BatchNormalization(name="batch_norm_calidad")(x_cal)
    x_cal = layers.Dropout(0.40, name="dropout_calidad")(x_cal)
    out_calidad = layers.Dense(1, activation='sigmoid', name="target_calidad")(x_cal)

    # Rama Producción Directa (Tasa Unitaria Logarítmica)
    x_prod = layers.Concatenate(name="fusion_reinyectada_produccion")([combined, planting_meta, emb_variety])
    x_prod = layers.Dense(64, activation='swish', kernel_regularizer=regularizers.l2(1e-3), name="prod_head_1")(x_prod)
    x_prod = layers.Multiply(name="film_escala_produccion")([x_prod, gamma_prod])
    x_prod = layers.Add(name="film_sesgo_produccion")([x_prod, beta_prod])
    x_prod = layers.BatchNormalization(name="batch_norm_produccion_1")(x_prod)
    x_prod = layers.Dropout(0.25, name="dropout_produccion_1")(x_prod)

    prod_residual = layers.Dense(32, activation='swish', kernel_regularizer=regularizers.l2(1e-3), name="prod_head_2")(x_prod)

    anfis_scaled = layers.Dense(32, use_bias=False, name="proyeccion_base_anfis")(anfis_promedio)
    anfis_scaled = layers.BatchNormalization(name="batch_norm_anfis_base")(anfis_scaled)

    x_final_prod = layers.Add(name="conexion_residual_produccion")([prod_residual, anfis_scaled])
    x_final_prod = layers.Dense(16, activation='swish', name="refinamiento_final_produccion")(x_final_prod)

    # Salida limpia de Tasa Unitaria Estandarizada
    out_produccion = layers.Dense(1, activation='linear', name="target_produccion")(x_final_prod)

    model = MultiLRModel(
        inputs=[input_clima, input_total_v],
        outputs=[out_calidad, out_produccion],
        penalizacion_mermas=fuerza_castigo,
        factor_prod=1.0
    )

    return model

def preparar_tensores_hibridos_v7_log(df_p, df_c, variety_to_int, climate_features, planting_features, max_dias=30, modo_inferencia=False):
    """
    Prepara tensores para ANFIS-v7.
    - En entrenamiento (modo_inferencia=False): Filtra prod <= 0 y genera etiquetas y_calidad y y_produccion.
    - En inferencia (modo_inferencia=True): No requiere Total_Produccion ni Calidad_Proporcion; solo construye tensores X_lstm y X_anfis.
    """
    X_lstm_list, X_anfis_list = [], []
    y_calidad, y_produccion = [], []
    original_indices = []

    features_locales = list(planting_features).copy()

    # Estandarización de orden estricto de columnas exógenas
    for col in ['Total_Plantas', 'GDC_Diario_Promedio', 'GDC_Acumulados_Ciclo', 'VPD_Medio_Ciclo']:
        if col in features_locales:
            features_locales.remove(col)

    features_locales.insert(0, 'VPD_Medio_Ciclo')
    features_locales.insert(0, 'GDC_Acumulados_Ciclo')
    features_locales.insert(0, 'GDC_Diario_Promedio')
    features_locales.insert(0, 'Total_Plantas')

    df_p_local = df_p.copy()
    df_c_local = df_c.copy()

    for col in ['GDC_Diario_Promedio', 'GDC_Acumulados_Ciclo', 'VPD_Medio_Ciclo']:
        if col not in df_p_local.columns:
            df_p_local[col] = 0.0

    if 'time' in df_c_local.columns:
        df_c_local = df_c_local.rename(columns={'time': 'Fecha'})

    df_p_local['Fecha_Siembra'] = pd.to_datetime(df_p_local['Fecha_Siembra'])
    df_p_local['Fecha_Corte']   = pd.to_datetime(df_p_local['Fecha_Corte'])
    df_c_local['Fecha']         = pd.to_datetime(df_c_local['Fecha'])

    # Renombrado defensivo
    for col in climate_features:
        if col not in df_c_local.columns:
            for c_real in df_c_local.columns:
                if col.split('_')[0] in c_real:
                    df_c_local = df_c_local.rename(columns={c_real: col})

    for original_index, lote in df_p_local.iterrows():
        # En modo entrenamiento se exige validación de producción
        if not modo_inferencia:
            prod_val = float(lote.get('Total_Produccion', 0.0))
            if prod_val <= 0.0 or pd.isna(prod_val):
                continue

        f_siembra = lote['Fecha_Siembra']
        f_corte   = lote['Fecha_Corte']

        mask_ciclo = (df_c_local['Fecha'] >= f_siembra) & (df_c_local['Fecha'] <= f_corte)
        clima_ciclo = df_c_local.loc[mask_ciclo]

        fecha_inicio_lstm = f_corte - pd.Timedelta(days=max_dias)
        mask_lstm = (df_c_local['Fecha'] >= fecha_inicio_lstm) & (df_c_local['Fecha'] <= f_corte)
        clima_ventana_lstm = df_c_local.loc[mask_lstm].sort_values('Fecha')[climate_features].values

        if len(clima_ventana_lstm) > 0 and len(clima_ciclo) > 0:
            X_lstm_list.append(clima_ventana_lstm)

            col_gdc = [c for c in clima_ciclo.columns if 'GDC' in str(c).upper()]
            total_gdc_ciclo = clima_ciclo[col_gdc[0]].sum() if col_gdc else 0.0

            col_vpd = [c for c in clima_ciclo.columns if 'VPD' in str(c).upper()]
            vpd_medio_ciclo = clima_ciclo[col_vpd[0]].mean() if col_vpd else 0.28

            dias_ciclo = max((f_corte - f_siembra).days, 1.0)
            tasa_gdc_diaria = total_gdc_ciclo / float(dias_ciclo)

            df_p_local.at[original_index, 'GDC_Acumulados_Ciclo'] = float(total_gdc_ciclo)
            df_p_local.at[original_index, 'GDC_Diario_Promedio']  = float(tasa_gdc_diaria)
            df_p_local.at[original_index, 'VPD_Medio_Ciclo']     = float(vpd_medio_ciclo)

            m = f_siembra.month
            s = f_siembra.isocalendar().week if hasattr(f_siembra.isocalendar(), 'week') else f_siembra.isocalendar()[1]
            tiempo_ciclico = [
                np.sin(2 * np.pi * m / 12), np.cos(2 * np.pi * m / 12),
                np.sin(2 * np.pi * s / 52), np.cos(2 * np.pi * s / 52)
            ]

            v_idx = variety_to_int[lote['Variedad']]
            one_hot_v = np.zeros(len(variety_to_int))
            one_hot_v[v_idx] = 1.0

            datos_siembra_actualizados = df_p_local.loc[original_index, features_locales].values.astype(float)
            vector_exogeno = np.concatenate([datos_siembra_actualizados, tiempo_ciclico, one_hot_v])
            X_anfis_list.append(vector_exogeno)

            if not modo_inferencia:
                proporcion_calidad_lote = float(lote['Calidad_Proporcion'])
                y_calidad.append(1.0 if proporcion_calidad_lote >= 1.0 else 0.0)
                target_prod_final = float(lote['PRODUCCION_LOG'])
                y_produccion.append(target_prod_final)

            original_indices.append(original_index)

    X_lstm_padded = pad_sequences(X_lstm_list, maxlen=max_dias, dtype='float32', padding='pre')

    return (X_lstm_padded,
            np.array(X_anfis_list).astype('float32'),
            np.array(y_calidad).astype('float32') if not modo_inferencia else None,
            np.array(y_produccion).astype('float32') if not modo_inferencia else None,
            np.array(original_indices))


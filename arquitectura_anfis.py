@keras.utils.register_keras_serializable()
class DynamicLossWeights(keras.callbacks.Callback):
    """Callback dinámico para ajustar el peso de la pérdida de producción."""
    def __init__(self, start_weight=1.0, end_weight=2.2, total_epochs=150, **kwargs):
        super().__init__(**kwargs)
        self.start_weight = float(start_weight)
        self.end_weight = float(end_weight)
        self.total_epochs = float(total_epochs)

    def on_epoch_begin(self, epoch, logs=None):
        progress = min(epoch / self.total_epochs, 1.0)
        current_weight = self.start_weight + (self.end_weight - self.start_weight) * progress

        # Asignación de pesos compatible con Keras 3 y MultiLRModel
        if hasattr(self.model, 'loss_weights'):
            self.model.loss_weights = {"target_calidad": 1.0, "target_produccion": current_weight}
        if hasattr(self.model, '_loss_weights_SaaS'):
            self.model._loss_weights_SaaS = {"target_calidad": 1.0, "target_produccion": current_weight}

    def get_config(self):
        config = super().get_config()
        config.update({
            "start_weight": self.start_weight,
            "end_weight": self.end_weight,
            "total_epochs": self.total_epochs
        })
        return config

@keras.utils.register_keras_serializable()
class VarietySpecificFuzzification(layers.Layer):
    """
    Capa de Fuzzificación corregida para ANFIS con soporte de serialización.
    """
    def __init__(self, num_mfs, num_features, num_varieties, expert_priors=None, **kwargs):
        super(VarietySpecificFuzzification, self).__init__(**kwargs)
        self.num_mfs = num_mfs
        self.num_features = num_features
        self.num_varieties = num_varieties
        self.expert_priors = expert_priors
        self.supports_masking = False

    def build(self, input_shape):
        mu_init = np.zeros((self.num_varieties, self.num_features), dtype=np.float32)
        sigma_init = np.ones((self.num_varieties, self.num_features), dtype=np.float32)

        if self.expert_priors is not None:
            ids_disponibles = sorted(list(self.expert_priors.keys()))
            for i in range(min(self.num_varieties, len(ids_disponibles))):
                v_id = ids_disponibles[i]
                params_lista = self.expert_priors[v_id]
                for j in range(min(self.num_features, len(params_lista))):
                    mu_init[i, j] = float(params_lista[j]['mu'])
                    sigma_init[i, j] = float(params_lista[j]['sigma'])

        self.mu = self.add_weight(
            name='mu',
            shape=(self.num_varieties, self.num_features),
            initializer=tf.keras.initializers.Constant(mu_init),
            trainable=True
        )

        self.sigma = self.add_weight(
            name='sigma',
            shape=(self.num_varieties, self.num_features),
            initializer=tf.keras.initializers.Constant(sigma_init),
            trainable=True
        )

        super(VarietySpecificFuzzification, self).build(input_shape)

    def call(self, inputs):
        x, v_idx = inputs
        v_idx = ops.cast(ops.reshape(v_idx, [-1]), "int32")

        batch_mu = ops.take(self.mu, v_idx, axis=0)
        batch_sigma = ops.take(self.sigma, v_idx, axis=0)

        x_expanded = ops.expand_dims(x, axis=-1)
        batch_mu_expanded = ops.expand_dims(ops.expand_dims(batch_mu, axis=1), axis=-1)
        batch_sigma_expanded = ops.expand_dims(ops.expand_dims(batch_sigma, axis=1), axis=-1)

        return ops.exp(-0.5 * ops.square((x_expanded - batch_mu_expanded) / (batch_sigma_expanded + 1e-6)))

    def get_config(self):
        # Esta función es vital para guardar/cargar el modelo
        config = super().get_config()
        config.update({
            "num_mfs": self.num_mfs,
            "num_features": self.num_features,
            "num_varieties": self.num_varieties,
            "expert_priors": self.expert_priors
        })
        return config


@keras.saving.register_keras_serializable()
class FuzzyRuleLayer(layers.Layer):
    """Evalúa la activación de las reglas difusas mediante producto cartesiano."""
    def __init__(self, num_mfs, num_features, **kwargs):
        super(FuzzyRuleLayer, self).__init__(**kwargs)
        self.num_mfs = num_mfs
        self.num_features = num_features
        self.num_rules = num_mfs ** num_features

    def call(self, inputs):
        """
        Calcula la activación de las reglas difusas mediante producto cartesiano.
        Entrada esperada: (batch_size, time_steps, num_features, num_mfs)
        Salida generada: (batch_size, time_steps, num_rules) donde num_rules = num_mfs ^ num_features
        """
        # 1. Obtener formas dinámicas (resiliente a batch sizes variables)
        s = ops.shape(inputs)
        batch_size, time_steps, num_features, num_mfs = s[0], s[1], s[2], s[3]

        # 2. Inicializar el producto cartesiano con la primera característica
        # rules tendrá forma inicial: (batch_size, time_steps, num_mfs)
        rules = inputs[:, :, 0, :]

        # 3. Iterar sobre las características restantes para completar el producto
        for i in range(1, num_features):
            # Expandimos dimensiones para preparar el producto externo
            # Reglas acumuladas: (batch_size, time_steps, reglas_actuales, 1)
            # Feature actual:    (batch_size, time_steps, 1, num_mfs)
            rules_expanded = ops.expand_dims(rules, axis=-1)
            feat_expanded = ops.expand_dims(inputs[:, :, i, :], axis=2)

            # Multiplicación broadcast (genera todas las combinaciones posibles)
            rules = rules_expanded * feat_expanded

            # 4. Aplanar las dimensiones de las reglas para la siguiente iteración
            # Resultado temporal: (batch_size, time_steps, reglas_actuales * num_mfs)
            rules = ops.reshape(rules, (batch_size, time_steps, -1))

        # 5. Verificación final de la forma de salida (batch_size, time_steps, num_rules)
        # self.num_rules debe ser igual al tamaño del último eje de 'rules'
        return rules

    def get_config(self):
        config = super(FuzzyRuleLayer, self).get_config()
        config.update({
            "num_mfs": self.num_mfs,
            "num_features": self.num_features
        })
        return config


@keras.saving.register_keras_serializable()
class NormalizationLayer(layers.Layer):
    """Aplica normalización L1 sobre las activaciones de las reglas difusas."""
    def __init__(self, **kwargs):
        super(NormalizationLayer, self).__init__(**kwargs)
        self.supports_masking = True

    def call(self, inputs):
        # Inputs shape: (batch_size, time_steps, num_rules)
        # Sum along the last axis (num_rules) and keep dimensions for broadcasting
        sum_of_rules = ops.sum(inputs, axis=-1, keepdims=True) + 1e-7
        return inputs / sum_of_rules

    def compute_mask(self, inputs, mask=None):
        return mask


@keras.saving.register_keras_serializable()
class SugenoDefuzzificationLayer_v2(layers.Layer):
    """
    Capa de Defuzzificación de Sugeno con inicialización opcional
    de reglas expertas parciales (Caja Gris).
    """
    def __init__(self, num_mfs, num_features, partial_rules=None, **kwargs):
        super(SugenoDefuzzificationLayer_v2, self).__init__(**kwargs)
        self.num_mfs = num_mfs
        self.num_features = num_features
        self.num_rules = num_mfs ** num_features
        self.partial_rules = partial_rules
        self.supports_masking = True

    def build(self, input_shape):
        # input_shape should be (norm_weights_shape, anfis_input_shape)
        # norm_weights_shape: (batch_size, time_steps, num_rules)
        # anfis_input_shape: (batch_size, time_steps, num_features)

        # Consequent parameters for Sugeno type: linear function of inputs
        # For each rule 'k': f_k = p_k * x1 + q_k * x2 + ... + r_k
        # So we need (num_rules, num_features + 1) for the coefficients (p, q, ..., r)
        # where the +1 is for the constant term 'r_k'.
        initial_consequents_coeffs = np.zeros((self.num_rules, self.num_features + 1), dtype=np.float32)

        # Initialize constant terms (last column) with 0.5 (or any sensible default)
        initial_consequents_coeffs[:, -1] = 0.5

        if self.partial_rules:
            # Apply expert priors to the constant term of the consequents
            for rule_idx in range(self.num_rules):
                # Decode rule_idx back to MF combination
                # e.g., for 3 MFs and 2 features (00, 01, 02, 10, ...)
                combination = []
                temp_idx = rule_idx
                for _ in range(self.num_features): # Iterate in reverse order of features
                    combination.insert(0, temp_idx % self.num_mfs)
                    temp_idx //= self.num_mfs

                for rule in self.partial_rules:
                    match = True
                    for feat_idx_rule, target_mf in rule['indices'].items():
                        if combination[feat_idx_rule] != target_mf: # Check if this combination matches partial rule
                            match = False
                            break
                    if match:
                        # Apply the impact to the constant term of the consequent
                        initial_consequents_coeffs[rule_idx, -1] = rule['impacto']

        self.consequents_coeffs = self.add_weight(
            name="consequents_coeffs",
            shape=(self.num_rules, self.num_features + 1),
            initializer=keras.initializers.Constant(initial_consequents_coeffs),
            trainable=True
        )
        super(SugenoDefuzzificationLayer_v2, self).build(input_shape)

    def call(self, inputs):
        # Inputs are (anfis_input, norm_weights)
        # anfis_input: (batch_size, time_steps, num_features) - These are the crisp inputs
        # norm_weights: (batch_size, time_steps, num_rules)
        anfis_input_crisp, norm_weights = inputs

        # Add a bias term (constant 1) to the crisp inputs for the constant coefficient 'r_k'
        # anfis_input_crisp_biased shape: (batch_size, time_steps, num_features + 1)
        bias_term = ops.ones_like(anfis_input_crisp[:, :, :1]) # (batch_size, time_steps, 1)
        anfis_input_crisp_biased = ops.concatenate([anfis_input_crisp, bias_term], axis=-1)

        # Calculate f_k for each rule:
        # f_k = (anfis_input_crisp_biased @ self.consequents_coeffs_k)
        # This operation is equivalent to (batch_size, time_steps, 1, num_features + 1) @ (1, num_features + 1, num_rules)
        # resulting in (batch_size, time_steps, 1, num_rules)

        # f_k will have shape (batch_size, time_steps, num_rules)
        # Each f_k is a linear combination of inputs for a specific rule
        # We need to compute f_k for all rules simultaneously
        f_k_values = ops.einsum('btf,rk->btr', anfis_input_crisp_biased, self.consequents_coeffs) # b:batch, t:time, f:features+bias, r:rules

        # Defuzzification: Sum(w_k_normalizado * f_k)
        # Result shape: (batch_size, time_steps, 1)
        output = ops.sum(norm_weights * f_k_values, axis=-1, keepdims=True)

        return output

    def compute_mask(self, inputs, mask=None):
        # The mask should be for the time_steps dimension, taken from anfis_input_crisp
        if mask is not None and isinstance(mask, (list, tuple)):
            # The first input (anfis_input_crisp) is typically masked
            return mask[0]
        return None

    def get_config(self):
        config = super(SugenoDefuzzificationLayer_v2, self).get_config()
        config.update({
            "num_mfs": self.num_mfs,
            "num_features": self.num_features,
            "partial_rules": self.partial_rules
        })
        return config



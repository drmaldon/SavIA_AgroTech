@keras.saving.register_keras_serializable(package="AgroTechFloricola")
class MultiLRModel(keras.Model):
    def __init__(self, inputs=None, outputs=None, penalizacion_mermas=2.20, factor_prod=1.0, **kwargs):
        super().__init__(inputs=inputs, outputs=outputs, **kwargs)
        self.penalizacion_mermas = float(penalizacion_mermas)
        self.factor_prod = float(factor_prod)
        self._loss_weights_SaaS = {"target_calidad": 1.0, "target_produccion": 1.0}

        self._bce_SaaS = keras.losses.BinaryCrossentropy(reduction=None)
        self._huber_SaaS = keras.losses.Huber(delta=1.0, reduction=None)

        self.loss_tracker = keras.metrics.Mean(name="loss")
        self.loss_cal_tracker = keras.metrics.Mean(name="loss_calidad")
        self.loss_prod_tracker = keras.metrics.Mean(name="loss_produccion")

    @property
    def metrics(self):
        return [self.loss_tracker, self.loss_cal_tracker, self.loss_prod_tracker] + super().metrics

    def _calcular_loss_colectiva(self, x, y_true, y_pred, sample_weight=None):
        p_cal = y_pred[0] if isinstance(y_pred, (list, tuple)) else y_pred
        p_prod = y_pred[1] if isinstance(y_pred, (list, tuple)) else y_pred

        pred_calidad = ops.reshape(p_cal, [-1, 1])
        pred_produccion = ops.reshape(p_prod, [-1, 1])

        if isinstance(y_true, dict):
            real_calidad = ops.reshape(y_true["target_calidad"], [-1, 1])
            real_produccion = ops.reshape(y_true["target_produccion"], [-1, 1])
        else:
            real_calidad = ops.reshape(y_true[0], [-1, 1])
            real_produccion = ops.reshape(y_true[1], [-1, 1])

        # 1. Pérdida Calidad Balanceada
        loss_cal_raw = self._bce_SaaS(real_calidad, pred_calidad)
        mascara_mermas = ops.cast(ops.equal(real_calidad, 0.0), dtype="float32")
        mascara_perfectos = ops.cast(ops.equal(real_calidad, 1.0), dtype="float32")
        factor_ponderado = (mascara_mermas * self.penalizacion_mermas) + (mascara_perfectos * 1.0)

        loss_cal_vector = loss_cal_raw * factor_ponderado

        # 2. Pérdida Producción Huber Asimétrica
        residual = real_produccion - pred_produccion
        loss_prod_raw = self._huber_SaaS(real_produccion, pred_produccion)

        pesos_pico = ops.where(residual > 0.0, 1.40, 1.00)

        meta_vars = x[1] if isinstance(x, (list, tuple)) else x
        total_plantas = ops.reshape(meta_vars[:, 0], [-1, 1])
        peso_lote = ops.clip(total_plantas / ops.maximum(ops.mean(total_plantas), 1.0), 0.5, 2.0)

        loss_prod_vector = loss_prod_raw * pesos_pico * peso_lote * self.factor_prod

        # -----------------------------------------------------------------
        # 💡 APLICACIÓN DE SAMPLE WEIGHTS POR VARIEDAD (SI EXISTEN)
        # -----------------------------------------------------------------
        if sample_weight is not None:
            if isinstance(sample_weight, dict):
                if "target_calidad" in sample_weight:
                    sw_cal = ops.reshape(sample_weight["target_calidad"], [-1, 1])
                    loss_cal_vector = loss_cal_vector * sw_cal
                if "target_produccion" in sample_weight:
                    sw_prod = ops.reshape(sample_weight["target_produccion"], [-1, 1])
                    loss_prod_vector = loss_prod_vector * sw_prod
            else:
                sw_general = ops.reshape(sample_weight, [-1, 1])
                loss_prod_vector = loss_prod_vector * sw_general

        loss_calidad_balanceada = ops.mean(loss_cal_vector)
        loss_produccion_final = ops.mean(loss_prod_vector)

        w_cal = float(self._loss_weights_SaaS.get("target_calidad", 1.0))
        w_prod = float(self._loss_weights_SaaS.get("target_produccion", 1.0))

        total_loss = (w_cal * loss_calidad_balanceada) + (w_prod * loss_produccion_final)
        return total_loss, loss_calidad_balanceada, loss_produccion_final, real_calidad, pred_calidad, real_produccion, pred_produccion

    def train_step(self, data):
        # -----------------------------------------------------------------
        # DESEMPAQUETADO DEFENSIVO SOPTORTANDO SAMPLE WEIGHTS
        # -----------------------------------------------------------------
        if len(data) == 3:
            x, y, sample_weight = data
        else:
            x, y = data
            sample_weight = None

        with tf.GradientTape() as tape:
            y_pred = self(x, training=True)
            total_loss, l_cal, l_prod, r_cal, p_cal, r_prod, p_prod = self._calcular_loss_colectiva(x, y, y_pred, sample_weight=sample_weight)

        trainable_vars = self.trainable_variables
        gradients = tape.gradient(total_loss, trainable_vars)
        gradients, _ = tf.clip_by_global_norm(gradients, 1.0)
        self.optimizer.apply_gradients(zip(gradients, trainable_vars))

        self.loss_tracker.update_state(total_loss)
        self.loss_cal_tracker.update_state(l_cal)
        self.loss_prod_tracker.update_state(l_prod)

        y_true_dict = {"target_calidad": r_cal, "target_produccion": r_prod}
        y_pred_dict = {"target_calidad": p_cal, "target_produccion": p_prod}

        metrics_logs = self.compute_metrics(x, y_true_dict, y_pred_dict, sample_weight=sample_weight)
        metrics_logs["loss"] = self.loss_tracker.result()
        metrics_logs["loss_calidad"] = self.loss_cal_tracker.result()
        metrics_logs["loss_produccion"] = self.loss_prod_tracker.result()
        return metrics_logs

    def test_step(self, data):
        # -----------------------------------------------------------------
        # DESEMPAQUETADO DEFENSIVO PARA VALIDACIÓN
        # -----------------------------------------------------------------
        if len(data) == 3:
            x, y, sample_weight = data
        else:
            x, y = data
            sample_weight = None

        y_pred = self(x, training=False)
        total_loss, l_cal, l_prod, r_cal, p_cal, r_prod, p_prod = self._calcular_loss_colectiva(x, y, y_pred, sample_weight=sample_weight)

        self.loss_tracker.update_state(total_loss)
        self.loss_cal_tracker.update_state(l_cal)
        self.loss_prod_tracker.update_state(l_prod)

        y_true_dict = {"target_calidad": r_cal, "target_produccion": r_prod}
        y_pred_dict = {"target_calidad": p_cal, "target_produccion": p_prod}

        metrics_logs = self.compute_metrics(x, y_true_dict, y_pred_dict, sample_weight=sample_weight)
        metrics_logs["loss"] = self.loss_tracker.result()
        metrics_logs["loss_calidad"] = self.loss_cal_tracker.result()
        metrics_logs["loss_produccion"] = self.loss_prod_tracker.result()
        return metrics_logs

    def get_config(self):
        config = super().get_config()
        config.update({
            "penalizacion_mermas": self.penalizacion_mermas,
            "factor_prod": self.factor_prod,
        })
        return config

    @classmethod
    def from_config(cls, config, custom_objects=None):
        return super().from_config(config, custom_objects=custom_objects)


def r2_keras(y_true, y_pred):
    SS_res = ops.sum(ops.square(y_true - y_pred))
    SS_tot = ops.sum(ops.square(y_true - ops.mean(y_true)))
    return (1.0 - SS_res / (ops.maximum(SS_tot, 1e-7)))